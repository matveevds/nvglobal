/**
 * Заглушка пустого блока для редактора.
 *
 * Шаблоны блоков выходят через `return`, когда поля не заполнены. На сайте это
 * правильно — пустой блок ничего не печатает. Но в блочном редакторе такой блок
 * получает нулевую высоту: его не видно и невозможно выделить, то есть и
 * заполнить. Поэтому в режиме предпросмотра печатаем видимую карточку-заглушку.
 *
 * Вызывать строго перед `return` в ветке «нет данных» и только с $is_preview
 * из области видимости шаблона блока.
 *
 * @param bool   $is_preview Флаг предпросмотра, который ACF передаёт в шаблон.
 * @param string $title      Название блока.
 * @param string $hint       Что сделать, чтобы блок заполнился.
 * @return string Готовая разметка или пустая строка на фронте.
 */
function nv_block_placeholder($is_preview, $title, $hint = '') {
    if (!$is_preview) {
        return '';
    }

    $icon = '<svg class="nv-block-placeholder__icon" width="24" height="24" viewBox="0 0 24 24" fill="none" aria-hidden="true" focusable="false">'
        . '<path fill-rule="evenodd" clip-rule="evenodd" d="M12 3.75C7.44329 3.75 3.75 7.44329 3.75 12C3.75 16.5558 7.44335 20.25 12 20.25C16.5567 20.25 20.25 16.5567 20.25 12C20.25 7.44329 16.5567 3.75 12 3.75ZM2.25 12C2.25 6.61479 6.61479 2.25 12 2.25C17.3852 2.25 21.75 6.61479 21.75 12C21.75 17.3852 17.3852 21.75 12 21.75C6.61479 21.75 2.25 17.3852 2.25 12Z" fill="currentColor"/>'
        . '<path fill-rule="evenodd" clip-rule="evenodd" d="M12 7.54102C12.4142 7.54102 12.75 7.8768 12.75 8.29102V12.75C12.75 13.1642 12.4142 13.5 12 13.5C11.5858 13.5 11.25 13.1642 11.25 12.75V8.29102C11.25 7.8768 11.5858 7.54102 12 7.54102ZM11.25 15.75C11.25 15.3358 11.5858 15 12 15H12.01C12.4242 15 12.76 15.3358 12.76 15.75C12.76 16.1642 12.4242 16.5 12.01 16.5H12C11.5858 16.5 11.25 16.1642 11.25 15.75Z" fill="currentColor"/>'
        . '</svg>';

    $html  = '<div class="nv-block-placeholder">';
    $html .= $icon;
    $html .= '<span class="nv-block-placeholder__title">' . esc_html($title) . '</span>';

    if ('' !== $hint) {
        $html .= '<span class="nv-block-placeholder__hint">' . esc_html($hint) . '</span>';
    }

    $html .= '</div>';

    return $html;
}
